"""Writes crates/snapling-translate/src/models.rs: pinned OPUS-MT files of each direction."""
import hashlib
import json
import urllib.request

BOTH = "ru de fr es it uk zh nl".split()
TO_EN = "pl tr ja ko".split()
PAIRS = [("en", x) for x in BOTH] + [(x, "en") for x in BOTH + TO_EN]


def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


rows = []
for a, b in PAIRS:
    name = f"opus-mt-{a}-{b}"
    base = f"https://huggingface.co/Xenova/{name}"
    tree = {x["path"]: x for x in json.loads(get(f"https://huggingface.co/api/models/Xenova/{name}/tree/main/onnx"))}
    enc = tree["onnx/encoder_model_quantized.onnx"]
    dec = tree["onnx/decoder_model_quantized.onnx"]
    tok = hashlib.sha256(get(f"{base}/resolve/main/tokenizer.json")).hexdigest()
    cfg = json.loads(get(f"{base}/resolve/main/config.json"))
    mb = (enc["size"] + dec["size"]) // 1048576
    rows.append((a, b, enc["lfs"]["oid"], dec["lfs"]["oid"], tok, cfg["pad_token_id"], cfg["eos_token_id"], cfg.get("decoder_start_token_id"), mb))
    print(rows[-1][:2], rows[-1][5:], flush=True)

out = ["//! Generated by tools/gen_models.py: OPUS-MT directions with pinned SHA-256.\n\n"]
out.append("pub struct Direction {\n    pub from: &'static str,\n    pub to: &'static str,\n    pub encoder: &'static str,\n    pub decoder: &'static str,\n    pub tokenizer: &'static str,\n    pub pad: i64,\n    pub eos: i64,\n    pub mb: u32,\n}\n\n")
out.append(f"pub const DIRECTIONS: [Direction; {len(rows)}] = [\n")
for a, b, e, d, t, pad, eos, start, mb in rows:
    assert start in (None, pad), (a, b, start, pad)
    out.append(f'    Direction {{\n        from: "{a}",\n        to: "{b}",\n        encoder: "{e}",\n        decoder: "{d}",\n        tokenizer: "{t}",\n        pad: {pad},\n        eos: {eos},\n        mb: {mb},\n    }},\n')
out.append("];\n")
open("crates/snapling-translate/src/models.rs", "w", encoding="utf-8", newline="\n").write("".join(out))
